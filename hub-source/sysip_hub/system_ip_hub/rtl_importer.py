from __future__ import annotations

import re
from pathlib import Path
from typing import Any


RTL_SUFFIXES = {".v", ".sv", ".vh", ".svh"}
SKIP_DIRS = {".git", ".svn", "node_modules", "build", "out", "report", "reports"}
MODULE_RE = re.compile(r"\bmodule\s+([A-Za-z_][\w$]*)\b(?P<header>[\s\S]*?);", re.IGNORECASE)
PARAM_RE = re.compile(
    r"\b(?:parameter|localparam)\b\s+(?:(?:integer|int|longint|shortint|byte|logic|bit|signed|unsigned)\s+)*(?:\[[^\]]+\]\s+)?(?P<name>[A-Za-z_][\w$]*)\s*(?:=\s*(?P<default>[^,;\n]+))?",
    re.IGNORECASE,
)
PORT_RE = re.compile(
    r"\b(?P<direction>input|output|inout)\b\s+(?P<qualifiers>(?:(?:wire|reg|logic|signed|unsigned|var)\s+)*)?(?P<width>\[[^\]]+\]\s+)?(?P<name>[A-Za-z_][\w$]*)",
    re.IGNORECASE,
)


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*[\s\S]*?\*/", " ", text)
    return re.sub(r"//[^\n]*", " ", text)


def _clean(value: str | None) -> str:
    return (value or "").strip()


def parse_rtl_file(path: Path, project_root: Path) -> list[dict[str, Any]]:
    raw = path.read_text(encoding="utf-8", errors="replace")
    text = strip_comments(raw)
    modules: list[dict[str, Any]] = []
    matches = list(MODULE_RE.finditer(text))
    for index, match in enumerate(matches):
        header = match.group("header")
        module_name = match.group(1)
        parameters = [
            {"name": m.group("name"), "default": _clean(m.group("default"))}
            for m in PARAM_RE.finditer(header)
        ]
        ports = [
            {
                "name": m.group("name"),
                "direction": m.group("direction").lower(),
                "width": _clean(m.group("width")),
            }
            for m in PORT_RE.finditer(header)
        ]
        body_end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        body = text[match.end():body_end]
        modules.append(
            {
                "name": module_name,
                "source_file": str(path.relative_to(project_root)),
                "parameters": parameters,
                "ports": ports,
                "line_count": raw.count("\n") + 1,
                "has_clock": bool(re.search(r"\b\w*(?:clk|clock|aclk|tclk|refclk)\w*\b", header + body, re.IGNORECASE)),
                "has_reset": bool(re.search(r"\b\w*(?:rst|reset|rst_n|reset_n|aresetn|perst)\w*\b", header + body, re.IGNORECASE)),
            }
        )
    return modules


def scan_project(project_root: Path, max_files: int = 5000) -> dict[str, Any]:
    root = project_root.expanduser().resolve()
    if not root.exists() or not root.is_dir():
        raise ValueError("project path must be an existing directory")
    files: list[Path] = []
    for path in root.rglob("*"):
        if any(part in SKIP_DIRS for part in path.parts):
            continue
        if path.is_file() and path.suffix.lower() in RTL_SUFFIXES:
            files.append(path)
            if len(files) >= max_files:
                break
    modules: list[dict[str, Any]] = []
    errors: list[dict[str, str]] = []
    for path in sorted(files):
        try:
            modules.extend(parse_rtl_file(path, root))
        except Exception as exc:
            errors.append({"file": str(path), "error": str(exc)})
    return {
        "project_root": str(root),
        "file_count": len(files),
        "module_count": len(modules),
        "modules": modules,
        "errors": errors,
    }


def make_draft(module: dict[str, Any], project_root: str, category: str = "imported_rtl") -> dict[str, Any]:
    module_name = module["name"]
    safe_name = re.sub(r"[^a-zA-Z0-9_-]+", "_", module_name).strip("_").lower() or "rtl_module"
    tags = ["rtl", "imported"]
    if module.get("has_clock"):
        tags.append("clocked")
    if module.get("has_reset"):
        tags.append("reset")
    return {
        "schema_version": 1,
        "name": safe_name,
        "display_name": module_name,
        "version": "draft",
        "kind": "rtl_component",
        "category": category,
        "description": f"Imported RTL module {module_name} from {module['source_file']}.",
        "tags": tags,
        "protocols": [],
        "parameters": module.get("parameters", []),
        "interfaces": module.get("ports", []),
        "source": {
            "project_root": project_root,
            "source_file": module.get("source_file"),
            "line_count": module.get("line_count"),
        },
        "features": [x for x, enabled in (("clocked", module.get("has_clock")), ("reset", module.get("has_reset"))) if enabled],
        "limitations": ["Draft generated by scanner; review parameters, ports and protocol semantics before reuse."],
        "verification": {"simulation": "not_run", "lint": "not_run", "synthesis": "not_run"},
        "files": {"rtl": [module.get("source_file")]},
    }
